export interface DescriptorDisplayInfo {
  primary: string;
  secondary?: string;
  fullLabel: string;
}

/**
 * Returns formatted sensory display info.
 * Prioritizes sensory reference first, followed by the official SCA descriptor name
 * (e.g. "Manzana verde" as primary and "(Ácido málico)" as secondary descriptor).
 * If the sensory reference is identical to the descriptor name, only the primary name is shown.
 */
export function getDescriptorDisplay(descriptor: {
  name: string;
  reference?: string;
  nameEn?: string;
}): DescriptorDisplayInfo {
  if (!descriptor) {
    return { primary: "", fullLabel: "" };
  }

  if (!descriptor.reference) {
    return {
      primary: descriptor.name,
      secondary: undefined,
      fullLabel: descriptor.name,
    };
  }

  // Clean reference from "(aproximación)", "Olor de ", "Aroma de ", etc.
  const cleanRef = descriptor.reference
    .replace(/\s*\(aproximación\)/gi, "")
    .replace(/\s*\(aprox\.\)/gi, "")
    .replace(/^Olor de\s+/i, "")
    .replace(/^Aroma de\s+/i, "")
    .replace(/,\s*maní tostado/i, "")
    .trim();

  const isDistinct =
    cleanRef.length > 0 &&
    cleanRef.toLowerCase() !== descriptor.name.toLowerCase();

  if (isDistinct) {
    return {
      primary: cleanRef,
      secondary: descriptor.name,
      fullLabel: `${cleanRef} (${descriptor.name})`,
    };
  }

  return {
    primary: descriptor.name,
    secondary: undefined,
    fullLabel: descriptor.name,
  };
}
